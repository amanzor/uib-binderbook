#!/usr/bin/env node
// ============================================================
//  Regenerates the ACORD 25 field list inside
//  supabase/functions/insured-portal/index.ts from acord25-map.js,
//  so the Client Portal fills the certificate exactly the way the
//  AMS Certificate Master does. Run after changing acord25-map.js:
//
//    node scripts/portal-acord-fields.js          # rewrite
//    node scripts/portal-acord-fields.js --check  # fail if stale
// ============================================================
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
global.window = {};
require(path.join(root, 'acord25-map.js'));
const A = window.ACORD25;
const fields = A.allFields().filter((f) => f.pdf).map((f) => {
    const o = { k: f.k, pdf: f.pdf, t: f.type === 'check' ? 'c' : f.type === 'yn' ? 'y' : 't' };
    if (f.mdy) o.mdy = 1;
    if (f.money) o.money = 1;
    return o;
});
const block = '// BEGIN ACORD25 FIELDS (generated by scripts/portal-acord-fields.js — do not edit by hand)\n' +
    'const ACORD25 = ' + JSON.stringify({ edition: A.EDITION, editionField: A.EDITION_FIELD, fields }) + ';\n' +
    '// END ACORD25 FIELDS';

const file = path.join(root, 'supabase/functions/insured-portal/index.ts');
const src = fs.readFileSync(file, 'utf8');
const re = /\/\/ BEGIN ACORD25 FIELDS[\s\S]*?\/\/ END ACORD25 FIELDS/;
if (!re.test(src)) { console.error('Markers not found in ' + file); process.exit(2); }
const out = src.replace(re, block);
if (process.argv.includes('--check')) {
    if (out !== src) { console.error('insured-portal ACORD 25 field list is stale — run node scripts/portal-acord-fields.js'); process.exit(1); }
    console.log('insured-portal ACORD 25 field list is current');
} else {
    fs.writeFileSync(file, out);
    console.log('Wrote ' + fields.length + ' fields into ' + path.relative(root, file));
}
